"""
utils.generate_test_results_rst
===================================

Generates ``docs/source/qa/test_results.rst`` from a real ``junit.xml`` a pytest run already
produced (``tox -e py312``, or any ``pytest ... --junitxml=results/pytest_test_results/junit.xml``
invocation) -- the one QA page with numbers that cannot be produced by collection alone, since it
reports what actually passed, failed, or errored, not what exists.

Matches each junit testcase back to the TC id :mod:`utils.generate_qa_docs` assigned to the same
test (both derive the id the same way, via :func:`utils.qa_report_lib.assign_tc_ids`, numbered in
the order the junit file lists them per type -- junit preserves pytest's own collection order) and
to its ``REQ-*`` ids from the catalogue, via a second, markers-only collection pass.

Run by hand (no CI in this project): ``python -m utils.generate_test_results_rst``. Refuses to run,
with a clear message instead of a traceback, if no junit.xml exists yet.
"""

from __future__ import annotations

import datetime
import pathlib
import xml.etree.ElementTree as ET

from utils.check_traceability import collect_requirement_coverage
from utils.qa_report_lib import TEST_TYPE_ORDER, assign_tc_ids, render_list_table, type_from_node_id

REPO_ROOT = pathlib.Path(__file__).resolve().parent.parent
JUNIT_PATH = REPO_ROOT / "results" / "pytest_test_results" / "junit.xml"
QA_DOCS_DIR = REPO_ROOT / "docs" / "source" / "qa"

_BANNER = (
    ".. This page is generated by ``python -m utils.generate_test_results_rst`` from a real "
    "``results/pytest_test_results/junit.xml`` (produced by ``tox -e py312``). Do not hand-edit it "
    "-- rerun the suite and regenerate.\n\n"
)


def _node_id_from_junit(classname: str, name: str) -> str:
    """
    Reconstruct a pytest node id (``tests/unit/test_foo.py::test_bar``) from junit's own
    ``classname``/``name`` attributes, which junit writes as a dotted module path, not a file path.
    """
    module_path = classname.replace(".", "/") + ".py"
    return f"{module_path}::{name}"


def parse_junit(path: pathlib.Path) -> dict:
    """
    Parse a junit.xml produced by pytest into a plain dict:
    ``{"generated": iso-str-or-None, "totals": {...}, "cases": [...]}``.

    Each case is ``{"node_id", "status" ("passed"/"failed"/"error"/"skipped"), "duration"}``.
    """
    if not path.exists():
        raise SystemExit(
            f"No junit.xml at {path}. Run the suite with --junitxml first, e.g.:\n"
            f"  pytest tests --ignore=tests/e2e --junitxml={path}\n"
            f"or: tox -e py312"
        )
    root = ET.parse(path).getroot()
    suite = root if root.tag == "testsuite" else root.find("testsuite")
    if suite is None:
        raise SystemExit(f"{path} does not look like a pytest junit.xml (no <testsuite> element)")

    generated = suite.get("timestamp")
    cases = []
    for case in suite.findall("testcase"):
        node_id = _node_id_from_junit(case.get("classname", ""), case.get("name", ""))
        if case.find("failure") is not None:
            status = "failed"
        elif case.find("error") is not None:
            status = "error"
        elif case.find("skipped") is not None:
            status = "skipped"
        else:
            status = "passed"
        cases.append({"node_id": node_id, "status": status, "duration": float(case.get("time", 0.0))})

    totals = {
        "total": int(suite.get("tests", len(cases))),
        "failed": int(suite.get("failures", 0)),
        "error": int(suite.get("errors", 0)),
        "skipped": int(suite.get("skipped", 0)),
        "duration": float(suite.get("time", sum(c["duration"] for c in cases))),
    }
    totals["passed"] = totals["total"] - totals["failed"] - totals["error"] - totals["skipped"]
    return {"generated": generated, "totals": totals, "cases": cases}


def build_test_results_rst(junit_data: dict, catalogue_coverage: dict[str, list[str]]) -> str:
    """Render test_results.rst: a summary table, then one table per test layer."""
    generated = junit_data["generated"] or datetime.datetime.now(datetime.timezone.utc).isoformat()
    totals = junit_data["totals"]
    cases = junit_data["cases"]

    node_ids_by_type: dict[str, list[str]] = {t: [] for t in TEST_TYPE_ORDER}
    for case in cases:
        try:
            test_type = type_from_node_id(case["node_id"])
        except ValueError:
            continue
        node_ids_by_type[test_type].append(case["node_id"])
    tc_ids = assign_tc_ids(node_ids_by_type)

    # Invert catalogue_coverage (req_id -> [node_id]) into node_id -> [req_id] for display.
    req_ids_by_node: dict[str, list[str]] = {}
    for req_id, node_ids in catalogue_coverage.items():
        for node_id in node_ids:
            req_ids_by_node.setdefault(node_id, []).append(req_id)

    summary_rows = [
        [
            generated,
            str(totals["total"]),
            str(totals["passed"]),
            str(totals["failed"]),
            str(totals["error"]),
            str(totals["skipped"]),
            "0",  # No-run: this page only ever reports what the parsed junit.xml actually ran.
            f"{totals['duration']:.1f}",
        ]
    ]

    sections = [
        "Test Results",
        "==============",
        "",
        _BANNER.rstrip(),
        "",
        "Re-run ``python -m utils.generate_test_results_rst`` after a test run to refresh this page.",
        "",
        render_list_table(
            ["Generated", "Total", "Passed", "Failed", "Error", "Skipped", "No-run", "Duration (s)"],
            summary_rows,
            [16, 8, 8, 8, 8, 8, 8, 10],
        ),
    ]

    by_type: dict[str, list[dict]] = {t: [] for t in TEST_TYPE_ORDER}
    for case in cases:
        try:
            test_type = type_from_node_id(case["node_id"])
        except ValueError:
            continue
        by_type[test_type].append(case)

    for test_type in TEST_TYPE_ORDER:
        type_cases = by_type[test_type]
        if not type_cases:
            continue
        sections.append("")
        sections.append(test_type)
        sections.append("~" * len(test_type))
        sections.append("")
        rows = []
        for case in type_cases:
            tc_id = tc_ids.get(case["node_id"], "-")
            req_ids = ", ".join(req_ids_by_node.get(case["node_id"], [])) or "-"
            title = case["node_id"].split("::")[-1]
            rows.append([tc_id, req_ids, title, case["status"], f"{case['duration']:.3f}"])
        sections.append(
            render_list_table(["TC-ID", "REQ-IDS", "Title", "Status", "Duration (s)"], rows, [10, 16, 40, 10, 10])
        )

    return "\n".join(sections) + "\n"


def main() -> None:
    junit_data = parse_junit(JUNIT_PATH)
    coverage, _all_marked_ids = collect_requirement_coverage()
    content = build_test_results_rst(junit_data, coverage)

    QA_DOCS_DIR.mkdir(parents=True, exist_ok=True)
    out_path = QA_DOCS_DIR / "test_results.rst"
    out_path.write_text(content, encoding="utf-8", newline="\n")
    print("wrote", out_path)


if __name__ == "__main__":
    main()
